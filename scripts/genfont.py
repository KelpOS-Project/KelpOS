#!/usr/bin/env python3
"""Generate kernel/font.c from a PSF1/PSF2 console font.

Source font: kbd package console fonts (GPL-2.0+). We embed the bitmap
glyph data only; kbd is Free Software, so this stays FOSS-compatible.

Usage: python3 scripts/genfont.py > kernel/font.c
"""
import gzip
import struct
import sys
import glob

CANDIDATES = [
    "/usr/lib/kbd/consolefonts/default8x16.psfu.gz",
    "/usr/share/consolefonts/default8x16.psfu.gz",
    "/usr/lib/kbd/consolefonts/cp850-8x16.psfu.gz",
]

def find_font():
    import os
    env = os.environ.get("KELPOS_FONT")
    if env:
        return env
    for c in CANDIDATES:
        if glob.glob(c):
            return c
    raise SystemExit("no PSF font found; set KELPOS_FONT=/path/to/font.psfu.gz")

def load(path):
    if path.endswith(".gz"):
        d = gzip.open(path, "rb").read()
    else:
        d = open(path, "rb").read()
    if d[:2] == b"\x36\x04":  # PSF1
        height = d[3]
        if d[4] & 0x2:  # two 512-char tables
            raise SystemExit("PSF1 512-char fonts not supported")
        glyphs, width, height, off = 512, 8, height, 4
    elif d[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        _, _, hdr, _, count, charsize, height, width = struct.unpack("<IIIIIIII", d[:32])
        glyphs, width, height, off = count, width, height, hdr
    else:
        raise SystemExit("not a PSF font")
    if width != 8 or height != 16:
        raise SystemExit(f"need an 8x16 font, got {width}x{height}")
    rowbytes = (width + 7) // 8
    data = []
    for i in range(min(glyphs, 256)):
        g = d[off + i * charsize : off + (i + 1) * charsize]
        data.append(g[: rowbytes * height])
    return data

def main():
    path = find_font()
    data = load(path)
    while len(data) < 256:
        data.append(bytes(16))
    print("/* kernel/font.c — embedded 8x16 bitmap font (glyphs 0..255)")
    print(" * Generated by scripts/genfont.py from %s" % path.split("/")[-1])
    print(" * Glyph bitmaps taken from the kbd console-font package (GPL-2.0+). */")
    print("#include <stdint.h>")
    print("#include <stddef.h>")
    print()
    print("const uint8_t font8x16[256][16] = {")
    for i, g in enumerate(data):
        rows = ", ".join(f"0x{b:02x}" for b in g)
        label = ""
        if 32 <= i < 127:
            label = f" /* '{chr(i)}' */"
        print(f"    {{ {rows}, }},{label}")
    print("};")

if __name__ == "__main__":
    main()
