#!/usr/bin/env python3
"""Compute the optional-package selection for the KelpOS build.

Usage: python3 scripts/pkgconf.py '<PKGS>'
Writes a pkgconf.h fragment to stdout.

Accepted words:
  all            every optional package (default)
  all-<pkg>      all except <pkg> (may repeat)
  -<pkg>         remove <pkg> (may repeat)
  <pkg>          add <pkg>
"""
import sys

ALL = ["fs", "users", "fastfetch", "diskfs", "about", "mem", "crc", "cowsay", "fortune", "crash"]

arg = sys.argv[1] if len(sys.argv) > 1 else "all"
words = arg.split() or ["all"]

sel: list[str] = []
for w in words:
    if w == "all":
        sel = list(ALL)
    elif w.startswith("all-"):
        base = sel or ALL
        sel = [p for p in base if p != w[4:]]
    elif w.startswith("-") and len(w) > 1:
        base = sel or ALL
        sel = [p for p in base if p != w[1:]]
    elif w in ALL:
        if w not in sel:
            sel.append(w)
    else:
        sys.exit(f"pkgconf: unknown package '{w}' (known: {', '.join(ALL)})")

out = [f"/* generated by scripts/pkgconf.py from PKGS = '{arg}' */\n"]
for p in ALL:
    if p in sel:
        out.append(f"#define KELPOS_PKG_{p.upper()} 1\n")
sys.stdout.write("".join(out))
